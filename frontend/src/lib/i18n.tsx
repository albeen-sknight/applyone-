export type TranslationKey = keyof typeof translations.es;

type I18nContextValue = {
  language: OwnerLanguage;
  setLanguage: (language: OwnerLanguage) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function storedLanguage(): OwnerLanguage {
  if (typeof window === "undefined") return "es";
  return window.localStorage.getItem(languageStorageKey) === "en" ? "en" : "es";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<OwnerLanguage>(storedLanguage);

  useEffect(() => {
    window.localStorage.setItem(languageStorageKey, language);
  }, [language]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage: setLanguageState,
      toggleLanguage: () => setLanguageState((current) => (current === "es" ? "en" : "es")),
      t: (key) => translations[language][key] || translations.es[key]
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider.");
  }
  return context;
}
